export function buildUserContent({ fields }) {
  const topic = fields?.topic || "";
  const platform = fields?.platform || "";
  const length = fields?.length || "";

  const lines = [`我想拍的內容：${topic}`];
  if (platform) lines.push(`要發在：${platform}`);
  if (length) lines.push(`大概想拍：${length}`);

  return lines.join("\n");
}
