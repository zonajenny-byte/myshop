/**
 * 把前端送來的 history（{role, text}[]）轉成 Anthropic Messages API 格式，
 * 再把這一輪使用者剛講的話（today）接在最後面。
 */
export function buildMessages({ history, today }) {
  const prior = (history || []).map((h) => ({
    role: h.role === "assistant" ? "assistant" : "user",
    content: h.text,
  }));
  return [...prior, { role: "user", content: today }];
}
